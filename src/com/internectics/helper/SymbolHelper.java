    public static boolean isSymbolIncluded (String str) {

        if ((str == null) || str.length() ==0) {
            return false;
        }

        for (int i = 0; i < mUnicodeArray.length; i++) {
            if (str.contains(mUnicodeArray[i])) {
                return true;
            }
        }

        return false;
    }


